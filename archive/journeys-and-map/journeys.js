//             distance_estimate, pace_tag, mood_tags, beats, path, ideal }
//
//   Beat    { id, order, location_label, lat, lng, trigger_type, text_line,
//             audio_line, guidance_intensity, guidance_cue }
//
// Two fields are additions to the spec, both needed to draw the map:
//   * lat / lng on a beat — where the key spot actually is.
//   * path — the walking line itself, traced by hand through the streets
//     between the beats. A routing service could generate this later; for now
//     it is a list of [lat, lng] corners, which is what the scout would give us.
//
// `ideal` is the same -1 to +1 trait profile the quiz uses, so a journey can be
// ranked against someone's answers. See rankByFit in quizData.js.
//
// KNOWN MANUAL STEP: `guidance_intensity` is set per beat by whoever walked the
// route. How much direction a stretch needs depends on how navigable it is in
// real life — a single riverside path needs none, a five-way Tokyo junction
// needs a lot. There is no way to work this out automatically yet, so it is a
// human judgement call, not a gap in the code.
//
//   silent    — say nothing; the walker taps to peek if they want a cue
//   light     — show a short passive cue for a moment
//   directive — show the direction straight away, this bit is easy to get wrong

